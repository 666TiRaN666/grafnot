export function tr(key: string, lang: Lang): string {
  const row = STR[key];
  // No raw keys in the UI: unknown keys render as an em dash and warn once
  // in the console so the gap is found in dev, not by users.
  if (!row) {
    console.warn(`i18n: missing key "${key}"`);
    return '—';
  }
  return row[lang];
}


